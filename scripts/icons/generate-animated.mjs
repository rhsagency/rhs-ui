/**
 * Generates animated icons from scripts/icons/animated-icons.mjs.
 *
 * An entry names a glyph of registry/icons/index.tsx and says which of its
 * subpaths move and how. The generator cuts the glyph's own path into those
 * parts, so an animated icon is always drawn exactly like its still glyph,
 * and writes one registry item per icon: registry/icons/animated/<slug>.tsx
 * plus its entry in registry/icons/registry.json, with the glyph and a usage
 * snippet in `meta` for rhsui.com.
 *
 *   node scripts/icons/generate-animated.mjs          write everything
 *   node scripts/icons/generate-animated.mjs --check  fail if a file is stale
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

import { ICONS } from "./animated-icons.mjs";
import { PRESETS } from "./motion-presets.mjs";

const root = path.resolve(import.meta.dirname, "..", "..");
const indexSource = readFileSync(path.join(root, "registry/icons/index.tsx"), "utf8");
const registryFile = path.join(root, "registry/icons/registry.json");
const registry = JSON.parse(readFileSync(registryFile, "utf8"));
const check = process.argv.includes("--check");
const HEADER = "// Generated by scripts/icons/generate-animated.mjs from scripts/icons/animated-icons.mjs. Edit the spec, not this file.";

/** Every `export const IconX = ... d="..."` of the glyph index. */
const GLYPHS = new Map([...indexSource.matchAll(/export const (Icon\w+) = \(p: IconProps\) => \(?\s*<Glyph\s+\{\.\.\.p\}\s+d="([^"]+)"/g)].map((m) => [m[1], m[2]]));
const subpaths = (d) => d.split(/(?=M)/).filter(Boolean);
const kebab = (glyph) => glyph.replace(/^Icon/, "").replace(/([a-z0-9])([A-Z])/g, "$1-$2").replace(/([A-Z])([A-Z][a-z])/g, "$1-$2").toLowerCase();
const pascal = (slug) => slug.split("-").map((part) => part[0].toUpperCase() + part.slice(1)).join("");
const words = (slug) => slug.replace(/-/g, " ");
const existing = new Set(registry.items.filter((item) => item.meta?.motion && !item.meta?.generated).map((item) => item.name));

const problems = [];
let written = 0;
const generatedNames = new Set();
for (const icon of ICONS) {
  const d = GLYPHS.get(icon.glyph);
  if (!d) {
    problems.push(`${icon.glyph}: no such glyph in registry/icons/index.tsx`);
    continue;
  }
  const slug = icon.slug ?? kebab(icon.glyph);
  const name = `animated-${slug}`;
  if (existing.has(name)) problems.push(`${name}: a hand-written animated icon already has this name`);
  if (generatedNames.has(name)) problems.push(`${name}: listed twice`);
  generatedNames.add(name);
  const pieces = subpaths(d);
  const used = new Set();
  const parts = icon.parts.map(([part, wanted, motion, options = {}]) => {
    const indices = wanted === "*" ? pieces.map((_, i) => i) : wanted;
    for (const index of indices) {
      if (index >= pieces.length) problems.push(`${name}: ${part} asks for subpath ${index}, ${icon.glyph} has ${pieces.length}`);
      if (used.has(index)) problems.push(`${name}: subpath ${index} is in two parts`);
      used.add(index);
    }
    const [preset, ...args] = Array.isArray(motion) ? motion : [motion];
    const make = PRESETS[preset];
    if (!make) problems.push(`${name}: unknown motion ${preset}`);
    const step = make ? make(...args) : { keyframes: [], duration: 0 };
    return { part, d: indices.map((i) => pieces[i]).join(""), step: { ...step, ...(options.delay ? { delay: options.delay } : {}), ...(options.origin ? { origin: options.origin } : {}), ...(options.duration ? { duration: options.duration } : {}) } };
  });
  const rest = pieces.filter((_, i) => !used.has(i)).join("");
  const exportName = `Icon${pascal(slug)}Animated`;
  const steps = parts.map(({ part, step }) => {
    const { draw, ...motion } = step;
    return { part, ...motion };
  });
  const motion = { steps, pause: icon.pause ?? 1400 };
  const element = ({ part, d: partD, step }) =>
    `      <path data-part=${JSON.stringify(part)} d=${JSON.stringify(partD)}${step.draw ? " pathLength={1} strokeDasharray={1}" : ""} style={{ transformBox: "fill-box" }} />`;
  const file = [
    HEADER,
    'import { AnimatedGlyph, type AnimatedIconProps, type IconMotion } from "@rhs-ui/icons/animated-icon";',
    "",
    `/** ${icon.description} */`,
    `const motion: IconMotion = ${JSON.stringify(motion, null, 2)};`,
    "",
    `export function ${exportName}(props: AnimatedIconProps) {`,
    "  return (",
    "    <AnimatedGlyph motion={motion} {...props}>",
    ...(rest ? [`      <path d=${JSON.stringify(rest)} />`] : []),
    ...parts.map(element),
    "    </AnimatedGlyph>",
    "  );",
    "}",
    "",
  ].join("\n");
  const target = path.join(root, "registry/icons/animated", `${slug}.tsx`);
  if (!existsSync(target) || readFileSync(target, "utf8") !== file) {
    if (check) problems.push(`${target}: stale, run node scripts/icons/generate-animated.mjs`);
    else writeFileSync(target, file);
    written++;
  }
  const usage = icon.usage ?? (icon.loop ? `<p className="flex items-center gap-2">\n  <${exportName} trigger="loop" />\n  ${icon.label}\n</p>` : `<Button variant="outline">\n  <${exportName} />\n  ${icon.label}\n</Button>`);
  const entry = {
    name,
    type: "registry:ui",
    title: `Animated ${words(slug)}`,
    description: icon.description,
    categories: ["icons", "animated"],
    meta: { tier: "free", version: "0.5.0", since: "0.5.0", status: "stable", preview: "inline", motion: "trigger", glyph: icon.glyph, usage, generated: true },
    dependencies: [],
    registryDependencies: ["https://rhsui.com/r/animated-icon.json"],
    files: [{ path: `registry/icons/animated/${slug}.tsx`, type: "registry:ui", target: `components/rhs-ui/icons/animated/${slug}.tsx` }],
  };
  const at = registry.items.findIndex((item) => item.name === name);
  if (at >= 0) registry.items[at] = entry;
  else registry.items.push(entry);
}
// A generated item whose spec entry was removed goes too.
registry.items = registry.items.filter((item) => !item.meta?.generated || generatedNames.has(item.name));

if (problems.length) {
  console.error(problems.map((p) => `generate-animated: ${p}`).join("\n"));
  process.exit(1);
}
const json = JSON.stringify(registry, null, 2) + "\n";
if (readFileSync(registryFile, "utf8") !== json) {
  if (check) {
    console.error("generate-animated: registry/icons/registry.json is stale");
    process.exit(1);
  }
  writeFileSync(registryFile, json);
}
console.log(`generate-animated: ${ICONS.length} icons, ${written} file(s) ${check ? "stale" : "written"}`);
